"""Generates src/creatures/CreatureTables.cpp from docs/specs/alpha-creatures-models.md:
Appendix A (the model table) and Appendix B (the per-type step of the appearance generator).
The tables are data written down in the spec; this script only changes their form.

Usage: python tools/gen_creature_tables.py   (from the AlphaVulkan folder)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / 'docs' / 'specs' / 'alpha-creatures-models.md'
OUT = ROOT / 'src' / 'creatures' / 'CreatureTables.cpp'
SLOTS = 2569

text = SPEC.read_text(encoding='utf-8')

# Appendix A: "   0: body2, body4, ..." rows of ten.
a = text[text.index('## Appendix A'):text.index('## Appendix B')]
keys = [None] * SLOTS
for m in re.finditer(r'^\s*(\d+):\s*(.*)$', a, re.M):
    base = int(m.group(1))
    for i, name in enumerate(n.strip() for n in m.group(2).split(',')):
        if name and name not in ('-', '—', '(empty)'):
            keys[base + i] = name
slot_of = {}
for i, k in enumerate(keys):
    if k is not None and k not in slot_of:
        slot_of[k] = i
# (Keys loaded into two slots are written with their slot in Appendix B, "foot (432)".)

PARTS = ['head', 'hair', 'hand', 'foot', 'body', 'tail', 'arm', 'wing']
SCALARS = ['head', 'body', 'hand', 'foot', 'arm', 'weapon', 'tail', 'shoulder', 'wing', 'bodyPitch']
VECTORS = ['box', 'handRot', 'angles', 'bodyOff', 'headOff', 'handOff', 'footOff', 'tailOff', 'wingOff']
SOURCES = {'fixed': 0, 'head choice': 1, 'hair choice': 2, 'draw': 3}

problems = []


def model_rule(entry, t):
    entry = entry.strip()
    part, _, rest = entry.partition(' ')
    if part not in PARTS:
        problems.append(f'type {t}: unknown part in "{entry}"')
        return None
    m = re.match(r'(head choice|hair choice|draw) mod (\d+) → (\d+)\.\.', rest)
    if m:
        return (part, SOURCES[m.group(1)], int(m.group(3)), int(m.group(2)))
    m = re.match(r'\S+ \((\d+)\)$', rest)
    if m:
        return (part, 0, int(m.group(1)), 0)
    if rest in slot_of:
        return (part, 0, slot_of[rest], 0)
    problems.append(f'type {t}: model rule left to code: "{entry}"')
    return None


def number(s):
    return float(s.replace('−', '-'))


rows = []
b = text[text.index('## Appendix B'):]
for line in b.splitlines():
    m = re.match(r'^\| (\d+) \|(.*)$', line)
    if not m:
        continue
    t = int(m.group(1))
    cells = [c.strip() for c in m.group(2).split('|')]
    models, flags, scalars, vectors = (cells + ['', '', '', ''])[:4]
    rules = [r for r in (model_rule(e, t) for e in models.split(';') if e.strip()) if r]
    flag = int(flags, 16) if flags else 0
    sc = {}
    for e in filter(None, (x.strip() for x in scalars.split(';'))):
        name, value = e.rsplit(' ', 1)
        try:
            sc[name] = number(value)
        except ValueError:
            problems.append(f'type {t}: scalar left to code: "{e}"')
    vec = {}
    for e in filter(None, (x.strip() for x in vectors.split(';'))):
        mm = re.match(r'(\w+) \(([^)]*)\)$', e)
        if not mm or mm.group(1) not in VECTORS:
            problems.append(f'type {t}: vector left to code: "{e}"')
            continue
        comps = [c.strip() for c in mm.group(2).split(',')]
        try:
            vec[mm.group(1)] = [None if c == '·' else number(c) for c in comps]
        except ValueError:
            problems.append(f'type {t}: vector left to code: "{e}"')
    rows.append((t, rules, flag, sc, vec))


def f(v):
    return f'{v!r}f' if '.' in repr(v) or 'e' in repr(v) else f'{v}.f'


# Box heights that the recordings show one rounding step off the decimal in the spec.
EXACT_BOX = {2.7: '2.6999998f', 3.24: '3.2400002f', 3.6: '3.6000001f', 5.4: '5.3999996f'}


out = []
out.append('// Generated by tools/gen_creature_tables.py from docs/specs/alpha-creatures-models.md')
out.append('// (Appendix A: the model table; Appendix B: the per-type step). Do not edit by hand.')
out.append('#include "creatures/CreatureTables.h"')
out.append('')
out.append('namespace creatures {')
out.append('')
out.append(f'const char *const MODEL_KEYS[MODEL_SLOTS] = {{')
for i in range(0, SLOTS, 6):
    out.append('    ' + ' '.join((f'"{k}",' if k else 'nullptr,') for k in keys[i:i + 6]))
out.append('};')
out.append('')
out.append('const TypeRecipe TYPE_RECIPES[TYPE_COUNT] = {')
by_type = {r[0]: r for r in rows}
for t in range(max(by_type) + 1):
    if t not in by_type:
        out.append('    {},')
        continue
    _, rules, flag, sc, vec = by_type[t]
    rs = ', '.join(f'{{Part::{p.capitalize()}, {s}, {base}, {mod}}}' for p, s, base, mod in rules)
    scal_mask = 0
    scal_vals = []
    for i, n in enumerate(SCALARS):
        if n in sc:
            scal_mask |= 1 << i
        scal_vals.append(f(sc.get(n, 0.0)))
    vec_mask = 0
    vec_vals = []
    for i, n in enumerate(VECTORS):
        comps = vec.get(n, [None, None, None])
        for k, c in enumerate(comps):
            if c is not None:
                vec_mask |= 1 << (3 * i + k)
            vec_vals.append(EXACT_BOX[c] if n == 'box' and c in EXACT_BOX else f(c if c is not None else 0.0))
    out.append(f'    {{{len(rules)}, {{{rs}}}, 0x{flag:x}, 0x{scal_mask:x}, {{{", ".join(scal_vals)}}}, 0x{vec_mask:x},')
    out.append(f'     {{{", ".join(vec_vals)}}}}}, // {t}')
out.append('};')
out.append('')
out.append('} // namespace creatures')
OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'{sum(k is not None for k in keys)} model slots, {len(rows)} types written to {OUT.relative_to(ROOT)}')
for p in problems:
    print('note:', p)
